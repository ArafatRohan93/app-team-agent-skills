def gen_button_themes(spec, dims):
    comp = spec.get("components") or {}
    f, o, t = comp.get("filledButton") or {}, comp.get("outlinedButton") or {}, comp.get("textButton") or {}

    def text_style(c, default="labelLarge"):
        return f"AppTypography.{c.get('textStyle', default)}"

    def height(c):
        return dim_ref(c.get("height", dims["sizes"]["buttonHeight"]), "sizes", dims, prefer="buttonHeight")

    fshape = shape_expr(f.get("radius", 9999), dims)
    fbg = color_ref(f.get("background", "primary"))
    ffg = color_ref(f.get("foreground", "onPrimary"))
    pressed = ""
    if f.get("pressedBackground"):
        pressed = f"""
  ).copyWith(
    backgroundColor: WidgetStateProperty.resolveWith((states) {{
      if (states.contains(WidgetState.disabled)) {{
        return colors.onSurface.withValues(alpha: 0.12);
      }}
      if (states.contains(WidgetState.pressed)) {{
        return {color_ref(f['pressedBackground'])};
      }}
      return {fbg};
    }}),
    overlayColor: const WidgetStatePropertyAll(Colors.transparent),"""

    o = {**{k: f[k] for k in ("radius", "height", "textStyle") if k in f}, **o}  # outlined inherits filled
    oshape = shape_expr(o.get("radius", 9999), dims)
    oside = f"BorderSide(color: {color_ref(o.get('border', 'outline'))}, width: {num(o.get('borderWidth', 1))})"
    obg = f"\n    backgroundColor: {color_ref(o['background'])}," if o.get("background") else ""
    tpad = ""
    if t.get("horizontalPadding") is not None:
        tpad = f"\n    padding: const EdgeInsets.symmetric(horizontal: {num(t['horizontalPadding'])}),"

    return f"""{HEADER}
import 'package:flutter/material.dart';

import '../tokens/app_colors.dart';
import '../tokens/app_dimensions.dart';
import '../tokens/app_typography.dart';

FilledButtonThemeData filledButtonTheme(
  ColorScheme colors,
  AppColorExtension appColors,
) => FilledButtonThemeData(
  style: FilledButton.styleFrom(
    backgroundColor: {fbg},
    foregroundColor: {ffg},
    minimumSize: const Size.fromHeight({height(f)}),
    shape: {fshape},
    textStyle: {text_style(f)},{pressed}
  ),
);

OutlinedButtonThemeData outlinedButtonTheme(
  ColorScheme colors,
  AppColorExtension appColors,
) => OutlinedButtonThemeData(
  style: OutlinedButton.styleFrom(
    foregroundColor: {color_ref(o.get('foreground', 'onSurface'))},{obg}
    side: {oside},
    minimumSize: const Size.fromHeight({height(o)}),
    shape: {oshape},
    textStyle: {text_style(o)},
  ),
);

TextButtonThemeData textButtonTheme(
  ColorScheme colors,
  AppColorExtension appColors,
) => TextButtonThemeData(
  style: TextButton.styleFrom(
    foregroundColor: {color_ref(t.get('foreground', 'primary'))},
    textStyle: {text_style(t)},{tpad}
  ),
);
"""


def gen_input_theme(spec, dims):
    i = (spec.get("components") or {}).get("input") or {}
    radius = dim_ref(i.get("radius", dims["radius"]["radiusMd"]), "radius", dims)
    height = dim_ref(i.get("height", dims["sizes"]["inputHeight"]), "sizes", dims, prefer="inputHeight")
    focus_w = num(i.get("focusBorderWidth", 2))
    no_border = ("OutlineInputBorder(borderRadius: BorderRadius.circular("
                 + radius + "), borderSide: BorderSide.none)") if i.get("border") == "none" else ""
    return f"""{HEADER}
import 'package:flutter/material.dart';

import '../tokens/app_colors.dart';
import '../tokens/app_dimensions.dart';

InputDecorationTheme inputDecorationTheme(
  ColorScheme colors,
  AppColorExtension appColors,
) {{
  OutlineInputBorder border(Color color, [double width = 1]) =>
      OutlineInputBorder(
        borderRadius: BorderRadius.circular({radius}),
        borderSide: BorderSide(color: color, width: width),
      );

  return InputDecorationTheme(
    filled: true,
    fillColor: {color_ref(i.get('fill', 'surfaceContainer'))},
    constraints: const BoxConstraints(minHeight: {height}),
    contentPadding: const EdgeInsets.symmetric(
      horizontal: {num(i.get('paddingHorizontal', 16))},
      vertical: {num(i.get('paddingVertical', 12))},
    ),
    border: {no_border if i.get('border') == 'none' else "border(" + color_ref(i.get('border', 'outline')) + ")"},
    enabledBorder: {no_border if i.get('border') == 'none' else "border(" + color_ref(i.get('border', 'outline')) + ")"},
    focusedBorder: border({color_ref(i.get('focusBorder', 'primary'))}, {focus_w}),
    errorBorder: border({color_ref(i.get('errorBorder', 'error'))}),
    focusedErrorBorder: border({color_ref(i.get('errorBorder', 'error'))}, {focus_w}),
  );
}}
"""


# Public names each token file defines (keep in sync with gen_colors / gen_typography / gen_dimensions).
TOKEN_IMPORTS = {"app_dimensions": ("AppDimensions",), "app_typography": ("AppTypography",),
                 "app_colors": ("AppColorExtension", "AppColorsLight")}


def prune_token_imports(text):
    """Drop `../tokens/<x>.dart` imports whose names the file doesn't use (a design with only literal radii…)."""
    for module, symbols in TOKEN_IMPORTS.items():
        line = f"import '../tokens/{module}.dart';\n"
        body = text.replace(line, "")
        if line in text and not any(re.search(rf"\b{sym}\b", body) for sym in symbols):
            text = body
    return re.sub(r"\n{3,}", "\n\n", text)


def gen_surface_themes(spec, dims):
    comp = spec.get("components") or {}
    card, chip = comp.get("card") or {}, comp.get("chip") or {}
    div, sheet = comp.get("divider") or {}, comp.get("bottomSheet") or {}

    card_radius = dim_ref(card.get("radius", dims["radius"]["radiusMd"]), "radius", dims)
    card_side = f", side: BorderSide(color: {color_ref(card['border'])})" if card.get("border") else ""
    card_color = f"\n  color: {color_ref(card['color'])}," if card.get("color") else ""

    chip_radius = dim_ref(chip.get("radius", dims["radius"]["radiusSm"]), "radius", dims)
    chip_bg = f"\n  backgroundColor: {color_ref(chip['background'])}," if chip.get("background") else ""
    chip_side = f"\n  side: BorderSide(color: {color_ref(chip['border'])})," if chip.get("border") else ""
    chip_label = ""
    if chip.get("textStyle") or chip.get("label"):
        base = f"AppTypography.{chip.get('textStyle', 'labelLarge')}"
        chip_label = (f"\n  labelStyle: {base}.copyWith(color: {color_ref(chip['label'])}),"
                      if chip.get("label") else f"\n  labelStyle: {base},")

    sheet_bg = color_ref(sheet.get("background", "surfaceContainerLow"))
    sheet_radius = dim_ref(sheet.get("topRadius", dims["radius"]["radiusXl"]), "radius", dims)
    barrier = color_ref(sheet.get("barrierColor", "scrim"))
    opacity = num(sheet.get("barrierOpacity", 0.32))

    typo_import = "import '../tokens/app_typography.dart';\n" if chip_label else ""
    return f"""{HEADER}
import 'package:flutter/material.dart';

import '../tokens/app_colors.dart';
import '../tokens/app_dimensions.dart';
{typo_import}
CardThemeData cardTheme(ColorScheme colors, AppColorExtension appColors) =>
    CardThemeData({card_color}
      elevation: {num(card.get('elevation', 0))},
      surfaceTintColor: Colors.transparent,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular({card_radius}){card_side},
      ),
    );

ChipThemeData chipTheme(ColorScheme colors, AppColorExtension appColors) =>
    ChipThemeData({chip_bg}{chip_side}{chip_label}
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular({chip_radius}),
      ),
    );

DividerThemeData dividerTheme(
  ColorScheme colors,
  AppColorExtension appColors,
) => DividerThemeData(
  color: {color_ref(div.get('color', 'outlineVariant'))},
  thickness: {num(div.get('thickness', 1))},
);

BottomSheetThemeData bottomSheetTheme(
  ColorScheme colors,
  AppColorExtension appColors,
) => BottomSheetThemeData(
  backgroundColor: {sheet_bg},
  modalBackgroundColor: {sheet_bg},
  modalBarrierColor: {barrier}.withValues(alpha: {opacity}),
  shape: RoundedRectangleBorder(
    borderRadius: BorderRadius.vertical(top: Radius.circular({sheet_radius})),
  ),
);
"""


