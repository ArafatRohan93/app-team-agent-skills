#!/usr/bin/env python3
"""Generate the Flutter theme of a flutter-app-structure app from a theme spec.

Reads design/theme.spec.json (see references/spec-format.md), validates it and
writes ONLY these files (all marked GENERATED):

  lib/shared/theme/tokens/app_colors.dart          _Palette → AppColorsLight/Dark → AppColorExtension
  lib/shared/theme/tokens/app_typography.dart      all 15 Material text roles + extra styles
  lib/shared/theme/tokens/app_text_extension.dart  context.appText.<extra>
  lib/shared/theme/tokens/app_dimensions.dart      spacing / radius / sizes (shell contract + extras)
  lib/shared/theme/component_themes/color_schemes.dart   ColorScheme.fromSeed + provided roles
  lib/shared/theme/component_themes/button_themes.dart
  lib/shared/theme/component_themes/input_decoration_theme.dart
  lib/shared/theme/component_themes/surface_themes.dart  card, chip, divider, bottom sheet
  lib/shared/theme/app_theme.dart, theme_context_ext.dart, theme.dart
  lib/shared/theme/preview/theme_preview_screen.dart     debug preview of every token
  test/shared/theme/{app_theme,theme_contrast,theme_preview_screen}_test.dart
  design/THEME_REPORT.md                                 mapping report for designer sign-off

Usage:
  python3 generate_theme.py --root . [--spec design/theme.spec.json] [--allow-open-conflicts] [--dry-run]
"""

