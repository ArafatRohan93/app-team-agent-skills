def gen_report(spec, dims, provenance, provisional, warnings, font_warning):
    light, dark = ts.mode_colors(spec, "light"), ts.mode_colors(spec, "dark")
    ext = ts.extension_colors(spec)
    typo = spec.get("typography") or {}
    roles, extras = typo.get("roles") or {}, typo.get("extras") or {}
    out = [f"# Theme report — {spec['name']}", ""]
    out.append(f"Generated {datetime.date.today().isoformat()} from `design/theme.spec.json` by the "
               "flutter-design-system-theme skill. Regenerate after every spec change.")
    out.append("")
    if provisional:
        out += ["> **PROVISIONAL** — some conflicts are unresolved and use the recommended value. "
                "Confirm them below, mark them resolved in the spec and regenerate.", ""]
    sources = spec.get("sources") or []
    if sources:
        out.append("**Sources:** " + "; ".join(f"`{s.get('file', s.get('id'))}` ({s.get('type')})" for s in sources))
        out.append("")

    conflicts = spec.get("conflicts") or []
    out += ["## Conflicts", ""]
    if conflicts:
        out += ["| Target | Candidates | Used | Status |", "|---|---|---|---|"]
        for c in conflicts:
            cands = "<br>".join(f"`{x.get('value')}` ← {x.get('source')}" for x in c.get("candidates", []))
            used = c.get("resolution", c.get("recommendation"))
            status = "resolved" if c.get("status") == "resolved" else f"**open** — {c.get('reason', '')}"
            out.append(f"| `{c['target']}` | {cands} | `{used}` | {status} |")
    else:
        out.append("None.")
    out.append("")

    out += ["## Colour roles", "", "| Role | Light | Dark |", "|---|---|---|"]
    for role in ts.COLOR_ROLES:
        lv = f"`{light[role]['value']}` ← {light[role].get('source', '')}" if role in light else "derived from seed"
        dv = f"`{dark[role]['value']}` ← {dark[role].get('source', '')}" if role in dark else "derived from seed"
        out.append(f"| `{role}` | {lv} | {dv} |")
    seed = spec.get("seed")
    out += ["", f"Seed: `{(seed or light['primary'])['value']}`, scheme variant "
                f"`{(spec.get('policy') or {}).get('schemeVariant', 'fidelity')}`.", ""]

    out += ["## Brand colours (`context.appColors`)", "", "| Name | Usage | Light | Dark |", "|---|---|---|---|"]
    for name, e in ext.items():
        how = {"border": "outline tone", "fill": "container tone"}.get(e.get("usage", "text"), "foreground tone")
        dv = f"`{e['dark']['value']}` ← {e['dark'].get('source', '')}" if e.get("dark") else f"derived (tonal, {how})"
        out.append(f"| `{name}` | {e.get('usage', 'text')} | `{e['light']['value']}` ← {e['light'].get('source', '')} | {dv} |")
    out.append("")

    family = (typo.get("fontFamily") or {}).get("value") or "platform default"
    fallback = ", ".join(typo.get("fontFamilyFallback") or []) or "—"
    out += ["## Typography", "", f"Font: **{family}**, fallback: {fallback}.", ""]
    if font_warning:
        out += [f"> ⚠️ {font_warning}", ""]
    out += ["| Role | Size / line | Weight | Tracking | From |", "|---|---|---|---|---|"]
    for role in ts.TYPE_ROLES:
        if role in roles:
            s = roles[role]
            out.append(f"| `{role}` | {num(s['fontSize'])} / {num(s.get('lineHeight', '-'))} | {s.get('fontWeight', 400)} "
                       f"| {num(s.get('letterSpacing', 0))} | `{s.get('token', role)}` ← {s.get('source', '')} |")
        else:
            size, line, weight, ls = ts.MATERIAL_TYPE_SCALE[role]
            out.append(f"| `{role}` | {size} / {line} | {weight} | {ls} | Material 3 default |")
    for name, s in extras.items():
        feats = f" features: {', '.join(s['fontFeatures'])}" if s.get("fontFeatures") else ""
        out.append(f"| `appText.{name}` | {num(s['fontSize'])} / {num(s.get('lineHeight', '-'))} | {s.get('fontWeight', 400)} "
                   f"| {num(s.get('letterSpacing', 0))} | `{s.get('token', name)}` ← {s.get('source', '')}{feats} |")
    out.append("")

    out += ["## Dimensions (`AppDimensions`)", "", "| Name | dp | From |", "|---|---|---|"]
    for group in ("spacing", "radius", "sizes"):
        for key, value in dims[group].items():
            out.append(f"| `{key}` | {num(value)} | {provenance[key]} |")
    out.append("")

    comps = spec.get("components") or {}
    out += ["## Components", ""]
    if comps:
        for name, props in comps.items():
            shown = ", ".join(f"{k}: `{v}`" for k, v in props.items() if k not in ("source", "note"))
            out.append(f"- **{name}** — {shown}" + (f" ← {props['source']}" if props.get("source") else "")
                       + (f"  \n  _Note: {props['note']}_" if props.get("note") else ""))
    else:
        out.append("None specified; shell defaults used.")
    out.append("")

    out += ["## Contrast (provided colours)", "",
            "Derived colours are checked by `test/shared/theme/theme_contrast_test.dart`.", "",
            "| Mode | Pair | Ratio | Min | Result |", "|---|---|---|---|---|"]
    for r in ts.contrast_results(spec):
        result = {"pass": "✅", "fail": "❌", "accepted": f"accepted — {r['reason']}"}[r["status"]]
        out.append(f"| {r['mode']} | `{r['pair']}` | {r['ratio']:.2f} | {r['min']} | {result} |")
    out.append("")

    unmapped = spec.get("unmapped") or []
    out += ["## Not mapped", ""]
    out += [f"- `{u.get('token')}` `{u.get('value', '')}` — {u.get('reason', '')}" for u in unmapped] or ["Nothing."]
    out.append("")
    notes = spec.get("notes") or []
    if notes:
        out += ["## Notes", ""] + [f"- {n}" for n in notes] + [""]
    if warnings:
        out += ["## Validator warnings", ""] + [f"- {w}" for w in warnings] + [""]
    return "\n".join(out)


