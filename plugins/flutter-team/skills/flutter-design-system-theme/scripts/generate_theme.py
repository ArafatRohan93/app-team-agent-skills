def font_declared(root, family):
    pubspec = (root / "pubspec.yaml").read_text()
    return bool(re.search(rf"family:\s*['\"]?{re.escape(family)}['\"]?\s*$", pubspec, re.M)) or "google_fonts:" in pubspec


def format_files(root, rels):
    uses_fvm = any((d / n).exists() for d in (root, root.parent) for n in (".fvmrc", ".fvm"))
    cmd = (["fvm", "dart"] if uses_fvm and shutil.which("fvm") else ["dart"]) + ["format", *rels]
    if shutil.which(cmd[0]):
        subprocess.run(cmd, cwd=root, capture_output=True, text=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=".", help="Flutter app root (a flutter-app-structure project)")
    ap.add_argument("--spec", default="design/theme.spec.json", help="Spec path, relative to --root")
    ap.add_argument("--allow-open-conflicts", action="store_true",
                    help="Generate a PROVISIONAL theme using each open conflict's current value")
    ap.add_argument("--dry-run", action="store_true", help="List the files that would be written")
    args = ap.parse_args()

    root = Path(args.root).resolve()
    if not (root / "lib/shared/theme/theme.dart").exists():
        sys.exit("lib/shared/theme/theme.dart not found — this generator targets apps built with the "
                 "flutter-app-structure skill. Bootstrap or migrate the app first.")
    try:
        spec = ts.load_spec(root / args.spec)
    except ts.SpecError as e:
        sys.exit(f"error: {e}")

    errors, warnings = ts.validate(spec, allow_open_conflicts=args.allow_open_conflicts)
    if errors:
        for e in errors:
            print(f"error: {e}")
        sys.exit(f"\n{len(errors)} error(s) — fix the spec (run validate_theme_spec.py for details).")
    provisional = any(c.get("status", "open") == "open" for c in spec.get("conflicts") or [])

    pkg = read_package(root)
    dims, provenance = resolve_dims(spec)
    palette = Palette()
    typo = spec.get("typography") or {}
    families = [f for f in [(typo.get("fontFamily") or {}).get("value"), *(typo.get("fontFamilyFallback") or [])] if f]
    missing = [f for f in families if not font_declared(root, f)]
    font_warning = None
    if missing:
        font_warning = (f"Font(s) not declared in pubspec.yaml: {', '.join(missing)} (no `family:` entry and no google_fonts). "
                        "Add the font files under assets/fonts/ and declare them — ask the user for the files or whether to "
                        "use google_fonts — otherwise text falls back to the platform font.")

    colors_dart = gen_colors(spec, palette)
    app_theme_test, contrast_test, preview_test = gen_tests(spec, pkg)
    files = {
        "lib/shared/theme/tokens/app_colors.dart": colors_dart,
        "lib/shared/theme/tokens/app_typography.dart": gen_typography(spec),
        "lib/shared/theme/tokens/app_text_extension.dart": gen_text_extension(spec),
        "lib/shared/theme/tokens/app_dimensions.dart": gen_dimensions(dims, provenance),
        "lib/shared/theme/component_themes/color_schemes.dart": gen_color_schemes(spec),
        "lib/shared/theme/component_themes/button_themes.dart": gen_button_themes(spec, dims),
        "lib/shared/theme/component_themes/input_decoration_theme.dart": gen_input_theme(spec, dims),
        "lib/shared/theme/component_themes/surface_themes.dart": gen_surface_themes(spec, dims),
        "lib/shared/theme/component_themes/app_bar_theme.dart": gen_app_bar_theme(spec),
        "lib/shared/theme/app_theme.dart": gen_app_theme(),
        "lib/shared/theme/theme_context_ext.dart": gen_context_ext(),
        "lib/shared/theme/theme.dart": gen_barrel(pkg),
        "lib/shared/theme/preview/theme_preview_screen.dart": gen_preview(spec, pkg),
        "test/shared/theme/app_theme_test.dart": app_theme_test,
        "test/shared/theme/theme_contrast_test.dart": contrast_test,
        "test/shared/theme/theme_preview_screen_test.dart": preview_test,
        "design/THEME_REPORT.md": gen_report(spec, dims, provenance, provisional, warnings, font_warning),
    }
    files = {rel: prune_token_imports(text) if rel.startswith("lib/shared/theme/component_themes/") else text
             for rel, text in files.items()}

    for rel, content in files.items():
        path = root / rel
        existed = path.exists()
        hand_written = existed and "GENERATED by the flutter-design-system-theme" not in path.read_text()
        label = "replace hand-written" if hand_written else ("update" if existed else "create")
        print(f"{'would ' if args.dry_run else ''}{label}: {rel}")
        if not args.dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if not args.dry_run:
        format_files(root, [r for r in files if r.endswith(".dart")])

    for w in warnings:
        print(f"warning: {w}")
    if font_warning:
        print(f"warning: {font_warning}")
    print("\nPROVISIONAL theme (open conflicts) — confirm them, mark resolved, regenerate." if provisional else
          "\nTheme generated.")
    print("Next: run `flutter analyze` and `flutter test` (prefix with fvm if used), open design/THEME_REPORT.md,\n"
          "and review ThemePreviewScreen in light and dark mode.")


