# ---------------------------------------------------------------- helpers


def camel(text):
    words = re.findall(r"[A-Za-z0-9]+", text)
    if not words:
        return "color"
    out = words[0][0].lower() + words[0][1:] + "".join(w[0].upper() + w[1:] for w in words[1:])
    return out if out[0].isalpha() else "c" + out


def num(v):
    if isinstance(v, float):
        v = round(v, 4)
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    return repr(v) if isinstance(v, float) else str(v)


def src(entry):
    if not isinstance(entry, dict):
        return ""
    s = entry.get("source", "")
    return f"  // {s}" if s else ""


def read_package(root):
    m = re.search(r"^name:\s*([A-Za-z0-9_]+)", (root / "pubspec.yaml").read_text(), re.M)
    if not m:
        sys.exit("Could not read `name:` from pubspec.yaml")
    return m.group(1)


class Palette:
    """Deduplicates raw colours and gives each a readable private name."""

    def __init__(self):
        self.by_value, self.names = {}, {}

    def add(self, entry, fallback):
        value = entry["value"].upper()
        if value in self.by_value:
            return self.by_value[value]
        base = camel(entry.get("name") or entry.get("token") or fallback)
        name, i = base, 2
        while name in self.names:
            name, i = f"{base}{i}", i + 1
        self.by_value[value], self.names[name] = name, (value, entry)
        return name

    def dart(self):
        lines = []
        for name, (value, entry) in self.names.items():
            if isinstance(entry, dict) and entry.get("source"):
                lines.append(f"  // {entry['source']}")
            lines.append(f"  static const {name} = Color({ts.argb_literal(value)});")
        return "\n".join(lines)


def border_ref(ref, width=None):
    """BorderSide expression for an input border; 'none' draws no border."""
    return "BorderSide.none" if ref == "none" else None


def color_ref(ref, colors_var="colors", ext_var="appColors"):
    return f"{ext_var}.{ref[4:]}" if ref.startswith("ext.") else f"{colors_var}.{ref}"


def dim_ref(value, group, dims, prefer=None):
    """Use an AppDimensions constant when one has exactly this value."""
    if prefer and dims[group].get(prefer) == value:
        return f"AppDimensions.{prefer}"
    matches = [k for k, v in dims[group].items() if v == value]
    return f"AppDimensions.{matches[0]}" if len(matches) == 1 else num(value)


def shape_expr(radius, dims):
    if radius is None:
        return None
    if radius >= 9999:
        return "const StadiumBorder()"
    return f"RoundedRectangleBorder(borderRadius: BorderRadius.circular({dim_ref(radius, 'radius', dims)}))"


