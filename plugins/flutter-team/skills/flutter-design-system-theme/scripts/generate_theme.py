def gen_colors(spec, palette):
    light, dark = ts.mode_colors(spec, "light"), ts.mode_colors(spec, "dark")
    ext = ts.extension_colors(spec)
    seed = spec.get("seed")

    light_lines = []
    if seed:
        light_lines.append(f"  static const seed = _Palette.{palette.add(seed, 'seed')};")
    else:
        light_lines.append("  static const seed = primary;")
    for role in ts.COLOR_ROLES:
        if role in light:
            light_lines.append(f"  static const {role} = _Palette.{palette.add(light[role], role)};")
    ext_light = []
    for name, entry in ext.items():
        ext_light.append(f"  static const {name} = _Palette.{palette.add(entry['light'], name)};")

    dark_lines = []
    for role in ts.COLOR_ROLES:
        if role in dark:
            dark_lines.append(f"  static const {role} = _Palette.{palette.add(dark[role], role + 'Dark')};")
    for name, entry in ext.items():
        if entry.get("dark"):
            dark_lines.append(f"  static const {name} = _Palette.{palette.add(entry['dark'], name + 'Dark')};")

    all_dark_ext = all(e.get("dark") for e in ext.values())
    fields = "\n".join(f"  final Color {n};" for n in ext)
    ctor = "\n".join(f"    required this.{n}," for n in ext)
    light_args = "\n".join(f"    {n}: AppColorsLight.{n}," for n in ext)
    derive_role = {"text": "text", "largeText": "text", "icon": "text", "border": "border", "fill": "fill"}
    dark_args = "\n".join(
        f"    {n}: AppColorsDark.{n}," if e.get("dark")
        else f"    {n}: _deriveDark(AppColorsLight.{n}, _DarkUsage.{derive_role[e.get('usage', 'text')]}),"
        for n, e in ext.items())
    copy_params = ", ".join(f"Color? {n}" for n in ext)
    copy_body = "\n".join(f"    {n}: {n} ?? this.{n}," for n in ext)
    lerp_body = "\n".join(f"      {n}: Color.lerp({n}, other.{n}, t)!," for n in ext)
    derive_fn = "" if all_dark_ext else '''
enum _DarkUsage { text, border, fill }

/// Dark-mode counterpart of a brand colour the design system only gave for
/// light mode, from Material's tonal palette of that colour: foregrounds
/// (text, icons) take the light dark-scheme tone, borders the subtle outline
/// tone, fills the container tone. Listed as "derived" in THEME_REPORT.md —
/// review it in the preview screen.
Color _deriveDark(Color light, _DarkUsage usage) {
  final scheme = ColorScheme.fromSeed(
    seedColor: light,
    brightness: Brightness.dark,
    dynamicSchemeVariant: DynamicSchemeVariant.fidelity,
  );
  return switch (usage) {
    _DarkUsage.text => scheme.primary,
    _DarkUsage.border => scheme.outlineVariant,
    _DarkUsage.fill => scheme.primaryContainer,
  };
}
'''
    dark_class = ("abstract final class AppColorsDark {\n" + "\n".join(dark_lines) + "\n}\n") if dark_lines else \
        "// No dark colours in the design system: the dark ColorScheme is derived from\n// AppColorsLight.seed (see color_schemes.dart).\n"

    return f"""{HEADER}
import 'package:flutter/material.dart';

// Layer 1: raw palette — private. Names come from the design system's tokens.
abstract final class _Palette {{
{palette.dart()}
}}

// Layer 2: semantic tokens. Only component_themes/ and AppColorExtension read
// these; widgets use `context.colors` / `context.appColors` so they stay
// correct in light and dark mode.
abstract final class AppColorsLight {{
{chr(10).join(light_lines)}

  // --- Brand colours Material's ColorScheme has no slot for ---
{chr(10).join(ext_light)}
}}

{dark_class}
/// Semantic colours Material's ColorScheme has no slot for.
/// Read with `context.appColors.<name>`.
@immutable
class AppColorExtension extends ThemeExtension<AppColorExtension> {{
  const AppColorExtension({{
{ctor}
  }});

  static const light = AppColorExtension(
{light_args}
  );

  static {'const' if all_dark_ext else 'final'} dark = AppColorExtension(
{dark_args}
  );

{fields}

  @override
  AppColorExtension copyWith({{{copy_params}}}) => AppColorExtension(
{copy_body}
  );

  @override
  AppColorExtension lerp(AppColorExtension? other, double t) {{
    if (other == null) return this;
    return AppColorExtension(
{lerp_body}
    );
  }}
}}
{derive_fn}"""


def gen_color_schemes(spec):
    variant = (spec.get("policy") or {}).get("schemeVariant", "fidelity")
    light, dark = ts.mode_colors(spec, "light"), ts.mode_colors(spec, "dark")

    def scheme(name, mode, roles, cls):
        overrides = "\n".join(f"  {r}: {cls}.{r}," for r in ts.COLOR_ROLES if r in roles)
        brightness = "  brightness: Brightness.dark,\n" if mode == "dark" else ""
        return (f"final {name} = ColorScheme.fromSeed(\n"
                f"  seedColor: AppColorsLight.seed,\n{brightness}"
                f"  dynamicSchemeVariant: DynamicSchemeVariant.{variant},\n{overrides}\n);\n")

    return f"""{HEADER}
import 'package:flutter/material.dart';

import '../tokens/app_colors.dart';

// Every role the design system provides is used exactly; every other role is
// derived from the seed by Material's tonal algorithm (see THEME_REPORT.md).

{scheme('lightColorScheme', 'light', light, 'AppColorsLight')}
{scheme('darkColorScheme', 'dark', dark, 'AppColorsDark')}"""


# ---------------------------------------------------------------- typography


def text_style_expr(style):
    parts = ["fontFamily: fontFamily", "fontFamilyFallback: fontFamilyFallback",
             f"fontSize: {num(style['fontSize'])}",
             f"fontWeight: FontWeight.w{style.get('fontWeight', 400)}"]
    if style.get("lineHeight"):
        parts.append(f"height: {num(style['lineHeight'])} / {num(style['fontSize'])}")
    ls = style.get("letterSpacing", 0)
    if ls:
        parts.append(f"letterSpacing: {num(ls)}")
    features = style.get("fontFeatures") or []
    if features:
        parts.append("fontFeatures: [" + ", ".join(f"FontFeature('{f}')" for f in features) + "]")
    return "TextStyle(\n    " + ",\n    ".join(parts) + ",\n  )"


def gen_typography(spec):
    typo = spec.get("typography") or {}
    roles, extras = typo.get("roles") or {}, typo.get("extras") or {}
    family = (typo.get("fontFamily") or {}).get("value")
    fallback = typo.get("fontFamilyFallback") or []
    lines = [
        f"  static const fontFamily = {repr(family)};" if family else "  static const String? fontFamily = null;",
        ("  static const fontFamilyFallback = [" + ", ".join(repr(f) for f in fallback) + "];")
        if fallback else "  static const List<String>? fontFamilyFallback = null;",
        "",
        "  // --- Material TextTheme roles (read via context.textTheme.<role>) ---",
    ]
    for role in ts.TYPE_ROLES:
        if role in roles:
            style = roles[role]
            lines.append(f"  /// {style.get('token', role)} — {style.get('source', '')}")
        else:
            size, line, weight, ls = ts.MATERIAL_TYPE_SCALE[role]
            style = {"fontSize": size, "lineHeight": line, "fontWeight": weight, "letterSpacing": ls}
            lines.append("  /// Material 3 default (not in the design system).")
        lines.append(f"  static const {role} = {text_style_expr(style)};")
        lines.append("")
    if extras:
        lines.append("  // --- Extra styles (read via context.appText.<name>) ---")
        for name, style in extras.items():
            lines.append(f"  /// {style.get('token', name)} — {style.get('source', '')}")
            lines.append(f"  static const {name} = {text_style_expr(style)};")
            lines.append("")
    theme_args = "\n".join(f"    {r}: {r}," for r in ts.TYPE_ROLES)
    return f"""{HEADER}
import 'package:flutter/material.dart';

/// Size, weight, line height and tracking only — colour comes from the theme.
abstract final class AppTypography {{
{chr(10).join(lines)}
  static const textTheme = TextTheme(
{theme_args}
  );
}}
"""


def gen_text_extension(spec):
    extras = list(((spec.get("typography") or {}).get("extras") or {}).keys())
    if not extras:
        return f"""{HEADER}
import 'package:flutter/material.dart';

/// Extra text styles beyond Material's TextTheme. The design system defines
/// none; add them under typography.extras in the spec.
@immutable
class AppTextExtension extends ThemeExtension<AppTextExtension> {{
  const AppTextExtension();

  factory AppTextExtension.withColor(Color color) => const AppTextExtension();

  @override
  AppTextExtension copyWith() => this;

  @override
  AppTextExtension lerp(AppTextExtension? other, double t) => this;
}}
"""
    ctor = "\n".join(f"    required this.{n}," for n in extras)
    with_color = "\n".join(f"    {n}: AppTypography.{n}.copyWith(color: color)," for n in extras)
    fields = "\n".join(f"  final TextStyle {n};" for n in extras)
    copy_params = ", ".join(f"TextStyle? {n}" for n in extras)
    copy_body = "\n".join(f"    {n}: {n} ?? this.{n}," for n in extras)
    lerp_body = "\n".join(f"      {n}: TextStyle.lerp({n}, other.{n}, t)!," for n in extras)
    return f"""{HEADER}
import 'package:flutter/material.dart';

import 'app_typography.dart';

/// Extra text styles beyond Material's TextTheme, coloured by the theme.
/// Read with `context.appText.<name>`.
@immutable
class AppTextExtension extends ThemeExtension<AppTextExtension> {{
  const AppTextExtension({{
{ctor}
  }});

  factory AppTextExtension.withColor(Color color) => AppTextExtension(
{with_color}
  );

{fields}

  @override
  AppTextExtension copyWith({{{copy_params}}}) => AppTextExtension(
{copy_body}
  );

  @override
  AppTextExtension lerp(AppTextExtension? other, double t) {{
    if (other == null) return this;
    return AppTextExtension(
{lerp_body}
    );
  }}
}}
"""


# ---------------------------------------------------------------- dimensions


def resolve_dims(spec):
    dims, provenance = {}, {}
    for group, contract in (("spacing", ts.CONTRACT_SPACING), ("radius", ts.CONTRACT_RADIUS),
                            ("sizes", ts.CONTRACT_SIZES)):
        values = spec.get(group) or {}
        dims[group] = {}
        for key, default in contract.items():
            if key in values:
                dims[group][key] = values[key]["value"]
                provenance[key] = values[key].get("source", "")
            else:
                dims[group][key] = default
                provenance[key] = "shell default (not in the design system)"
        for key, entry in values.items():
            if key not in contract:
                dims[group][key] = entry["value"]
                provenance[key] = entry.get("source", "")
    return dims, provenance


def gen_dimensions(dims, provenance):
    lines = []
    for group, title in (("spacing", "Spacing"), ("radius", "Radius"), ("sizes", "Component sizes")):
        lines.append(f"  // --- {title} ---")
        for key, value in dims[group].items():
            v = float(value)
            lines.append(f"  static const {key} = {num(v) if not v.is_integer() else f'{int(v)}.0'};  // {provenance[key]}")
        lines.append("")
    return f"""{HEADER}
/// Spacing, radius and size tokens. Widgets never use raw numbers for padding,
/// gaps or radii. The shell's contract names are always present.
abstract final class AppDimensions {{
{chr(10).join(lines).rstrip()}
}}
"""


